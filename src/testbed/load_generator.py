"""Compute load generator: deterministic CPU and memory contention on a device.

CPU contention is generated by running a tight computational loop for a
configurable fraction of each fixed time interval (the duty cycle), so that
the targeted percentage of one CPU core is kept busy on average; ``--cores``
runs that many workers. Memory contention is generated by allocating and
holding 1 KB byte arrays until the configured fraction of the device's memory
is in use, then releasing them at the end.

Modes:
  * ``fixed``: one CPU and one memory target for the whole duration;
  * ``continuous``: at the start of every cycle a new <CPU %, memory %> target
    is drawn uniformly within configurable ranges (seeded, so repeatable);
  * ``--regime light|moderate|heavy``: the ranges of Chapter 3
    (light 10-20 % CPU and 10-20 % memory, moderate 30-50 % and 30-40 %,
    heavy 60-80 % and 50-60 %), in continuous mode;
  * ``--processes N``: N fully busy processes, the background-process model of
    Chapter 4 (n_i continuously backlogged processes).

Usage::

    python -m src.testbed.load_generator --cpu 40 --memory 30 --duration 120
    python -m src.testbed.load_generator --regime heavy --cycle-s 10 --duration 300 --seed 7
    python -m src.testbed.load_generator --processes 2 --duration 60
"""

from __future__ import annotations

import argparse
import json
import multiprocessing
import os
import random
import signal
import sys
import threading
import time
from collections.abc import Callable
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import psutil

from src.common.clock import Clock, SystemClock

REGIMES: dict[str, tuple[tuple[float, float], tuple[float, float]]] = {
    "light": ((10.0, 20.0), (10.0, 20.0)),
    "moderate": ((30.0, 50.0), (30.0, 40.0)),
    "heavy": ((60.0, 80.0), (50.0, 60.0)),
}
MEMORY_BLOCK_BYTES = 1024
MEMORY_SAFETY_CAP_PERCENT = 95.0  # never push the device into swapping


@dataclass(frozen=True)
class LoadTarget:
    cpu_percent: float  # of one core, per worker
    memory_percent: float  # of total memory in use, system-wide


@dataclass(frozen=True)
class CycleLog:
    cycle: int
    wall_time_s: float
    target: LoadTarget
    memory_blocks: int


# --- CPU ------------------------------------------------------------------------


def run_duty_cycle(
    target_percent: float,
    period_s: float,
    should_stop: Callable[[], bool],
    clock: Clock | None = None,
    spin: Callable[[], None] | None = None,
) -> int:
    """Busy for ``target_percent`` of every period, idle for the rest, until stopped.

    Returns the number of completed periods. ``spin`` is called inside the busy
    loop (tests pass a function that advances a fake clock).
    """
    if not 0.0 <= target_percent <= 100.0:
        raise ValueError("target_percent must be in [0, 100]")
    if period_s <= 0:
        raise ValueError("period_s must be positive")
    clock = clock or SystemClock()
    period_ns = int(period_s * 1e9)
    busy_ns = int(period_ns * target_percent / 100.0)
    periods = 0
    while not should_stop():
        start = clock.perf_counter_ns()
        busy_until = start + busy_ns
        while clock.perf_counter_ns() < busy_until:
            if spin is not None:
                spin()
        remaining = (start + period_ns) - clock.perf_counter_ns()
        if remaining > 0:
            clock.sleep(remaining / 1e9)
        periods += 1
    return periods


def _cpu_worker(target_percent: float, period_s: float, stop: Any) -> None:
    run_duty_cycle(target_percent, period_s, stop.is_set)


class CpuLoad:
    """``cores`` worker processes, each keeping one core busy for ``target_percent``."""

    def __init__(self, cores: int, period_s: float) -> None:
        self.cores = cores
        self.period_s = period_s
        self._stop = multiprocessing.Event()
        self._workers: list[multiprocessing.Process] = []

    def start(self, target_percent: float) -> None:
        self.stop()
        self._stop = multiprocessing.Event()
        self._workers = [
            multiprocessing.Process(
                target=_cpu_worker, args=(target_percent, self.period_s, self._stop), daemon=True
            )
            for _ in range(self.cores)
        ]
        for worker in self._workers:
            worker.start()

    def stop(self) -> None:
        self._stop.set()
        for worker in self._workers:
            worker.join(timeout=2.0)
            if worker.is_alive():
                worker.terminate()
        self._workers = []

    @property
    def pids(self) -> list[int]:
        return [w.pid for w in self._workers if w.pid is not None]


# --- Memory ----------------------------------------------------------------------


class MemoryHolder:
    """Allocates 1 KB blocks until the system-wide memory in use reaches the target."""

    def __init__(
        self,
        total_bytes: int,
        used_bytes: Callable[[], int],
        block_bytes: int = MEMORY_BLOCK_BYTES,
        cap_percent: float = MEMORY_SAFETY_CAP_PERCENT,
    ) -> None:
        self.total_bytes = total_bytes
        self.used_bytes = used_bytes
        self.block_bytes = block_bytes
        self.cap_percent = cap_percent
        self._blocks: list[bytearray] = []

    @property
    def blocks(self) -> int:
        return len(self._blocks)

    @property
    def allocated_bytes(self) -> int:
        return len(self._blocks) * self.block_bytes

    def fill_to(self, target_percent: float) -> int:
        """Allocate or release blocks so that memory in use reaches the target.

        Returns the number of blocks held."""
        target_percent = min(target_percent, self.cap_percent)
        target_bytes = int(self.total_bytes * target_percent / 100.0)
        used = self.used_bytes()
        if used < target_bytes:
            missing = target_bytes - used
            for _ in range(missing // self.block_bytes):
                self._blocks.append(bytearray(self.block_bytes))
        elif used > target_bytes and self._blocks:
            surplus = used - target_bytes
            release = min(len(self._blocks), surplus // self.block_bytes)
            del self._blocks[len(self._blocks) - release :]
        return len(self._blocks)

    def release(self) -> None:
        self._blocks.clear()


def system_memory() -> tuple[int, Callable[[], int]]:
    """Total bytes and a callable that returns the bytes currently in use."""
    total = psutil.virtual_memory().total
    return total, lambda: int(psutil.virtual_memory().total - psutil.virtual_memory().available)


# --- Generator ------------------------------------------------------------------------


@dataclass
class LoadSpec:
    mode: str = "fixed"  # fixed | continuous
    cpu_percent: float = 0.0
    memory_percent: float = 0.0
    cpu_range: tuple[float, float] | None = None
    memory_range: tuple[float, float] | None = None
    cores: int = 1
    processes: int = 0  # > 0: N fully busy workers (Chapter 4 model); overrides cpu settings
    period_ms: float = 100.0
    cycle_s: float = 10.0
    duration_s: float | None = None
    seed: int = 0

    @classmethod
    def regime(cls, name: str, **overrides: Any) -> LoadSpec:
        cpu_range, memory_range = REGIMES[name]
        return cls(mode="continuous", cpu_range=cpu_range, memory_range=memory_range, **overrides)

    def targets(self, rng: random.Random) -> LoadTarget:
        if self.processes > 0:
            cpu = 100.0
        elif self.mode == "continuous" and self.cpu_range is not None:
            cpu = rng.uniform(*self.cpu_range)
        else:
            cpu = self.cpu_percent
        if self.mode == "continuous" and self.memory_range is not None:
            memory = rng.uniform(*self.memory_range)
        else:
            memory = self.memory_percent
        return LoadTarget(round(cpu, 2), round(memory, 2))

    @property
    def worker_count(self) -> int:
        return self.processes if self.processes > 0 else self.cores


class LoadGenerator:
    def __init__(
        self,
        spec: LoadSpec,
        *,
        clock: Clock | None = None,
        cpu_load: CpuLoad | None = None,
        memory: MemoryHolder | None = None,
        log_path: Path | None = None,
    ) -> None:
        self.spec = spec
        self.clock = clock or SystemClock()
        self.cpu = cpu_load or CpuLoad(spec.worker_count, spec.period_ms / 1000.0)
        if memory is None:
            total, used = system_memory()
            memory = MemoryHolder(total, used)
        self.memory = memory
        self.rng = random.Random(spec.seed)
        self.log_path = log_path
        self.cycles: list[CycleLog] = []
        self._stop = threading.Event()

    def stop(self) -> None:
        self._stop.set()

    def run(self) -> list[CycleLog]:
        started = self.clock.time()
        cycle = 0
        try:
            while not self._stop.is_set():
                if (
                    self.spec.duration_s is not None
                    and self.clock.time() - started >= self.spec.duration_s
                ):
                    break
                target = self.spec.targets(self.rng)
                if cycle == 0 or self.spec.mode == "continuous":
                    if target.cpu_percent > 0:
                        self.cpu.start(target.cpu_percent)
                    else:
                        self.cpu.stop()
                    blocks = self.memory.fill_to(target.memory_percent)
                else:
                    blocks = self.memory.blocks
                self.cycles.append(CycleLog(cycle, self.clock.time(), target, blocks))
                self._write_log()
                cycle += 1
                wait = self.spec.cycle_s
                if self.spec.duration_s is not None:
                    wait = min(wait, max(0.0, self.spec.duration_s - (self.clock.time() - started)))
                if self.spec.mode == "fixed" and self.spec.duration_s is None:
                    wait = self.spec.cycle_s  # keep the process alive until stopped
                self._wait(wait)
        finally:
            self.cpu.stop()
            self.memory.release()
            self._write_log(final=True)
        return self.cycles

    def _wait(self, seconds: float) -> None:
        if seconds <= 0:
            return
        if isinstance(self.clock, SystemClock):
            self._stop.wait(seconds)
        else:
            self.clock.sleep(seconds)

    def _write_log(self, final: bool = False) -> None:
        if self.log_path is None:
            return
        payload = {
            "spec": asdict(self.spec),
            "cycles": [asdict(c) for c in self.cycles],
            "finished": final,
        }
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.log_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate deterministic CPU and memory load.")
    parser.add_argument("--cpu", type=float, default=0.0, help="CPU %% of one core per worker")
    parser.add_argument("--memory", type=float, default=0.0, help="memory %% in use, system-wide")
    parser.add_argument("--cores", type=int, default=1, help="number of CPU workers")
    parser.add_argument("--processes", type=int, default=0, help="N fully busy processes")
    parser.add_argument("--mode", choices=["fixed", "continuous"], default="fixed")
    parser.add_argument("--cpu-range", type=float, nargs=2, metavar=("MIN", "MAX"))
    parser.add_argument("--memory-range", type=float, nargs=2, metavar=("MIN", "MAX"))
    parser.add_argument("--regime", choices=sorted(REGIMES))
    parser.add_argument("--period-ms", type=float, default=100.0, help="duty-cycle period")
    parser.add_argument("--cycle-s", type=float, default=10.0, help="resampling cycle")
    parser.add_argument(
        "--duration", type=float, default=None, help="seconds; default: until stopped"
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--log", type=Path, help="JSON log of applied targets")
    parser.add_argument("--tag", help="process tag (ignored; present for pkill -f)")
    return parser


def spec_from_args(args: argparse.Namespace) -> LoadSpec:
    common = {
        "cores": args.cores,
        "processes": args.processes,
        "period_ms": args.period_ms,
        "cycle_s": args.cycle_s,
        "duration_s": args.duration,
        "seed": args.seed,
    }
    if args.regime:
        return LoadSpec.regime(args.regime, **common)
    return LoadSpec(
        mode=args.mode,
        cpu_percent=args.cpu,
        memory_percent=args.memory,
        cpu_range=tuple(args.cpu_range) if args.cpu_range else None,
        memory_range=tuple(args.memory_range) if args.memory_range else None,
        **common,
    )


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = spec_from_args(args)
    generator = LoadGenerator(spec, log_path=args.log)

    def handle_signal(signum: int, _frame: Any) -> None:
        generator.stop()

    signal.signal(signal.SIGTERM, handle_signal)
    signal.signal(signal.SIGINT, handle_signal)
    print(f"load generator pid {os.getpid()}: {spec}", file=sys.stderr)
    cycles = generator.run()
    print(f"load generator finished after {len(cycles)} cycle(s)", file=sys.stderr)


if __name__ == "__main__":
    # The CPU workers are separate processes; keep this import-safe for multiprocessing.
    time.sleep(0)
    main()
